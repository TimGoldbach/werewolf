// ── Helpers ──────────────────────────────────────────────────────────────────

const ROLE_BY_ID = new Map(ROLE_CATALOG.map((r) => [r.id, r]))

export function getRole(id: string): RoleDef | undefined {
  return ROLE_BY_ID.get(id)
}

export function getRoleOrThrow(id: string): RoleDef {
  const role = ROLE_BY_ID.get(id)
  if (!role) throw new Error(`Unknown role: ${id}`)
  return role
}

export function rolesByCategory(category: RoleCategory): RoleDef[] {
  return ROLE_CATALOG.filter((r) => r.category === category)
}

export function hasArchetype(role: RoleDef, archetype: Archetype): boolean {
  return role.archetypes.includes(archetype)
}

/**
 * Order in which the roles present in the game are woken at night.
 * @param presentRoleIds  roles actually in play in this game
 * @param firstNight      first night (more setup roles) vs. later night
 */
export function nightWakeOrder(presentRoleIds: Iterable<string>, firstNight: boolean): string[] {
  const present = new Set(presentRoleIds)
  const order = firstNight ? FIRST_NIGHT_ORDER : REGULAR_NIGHT_ORDER
  return order.filter((id) => present.has(id))
}

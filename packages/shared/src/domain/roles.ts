/**
 * Canonical nightly wake order.
 *
 * Instead of two hand-maintained lists we derive the order deterministically from
 * the catalog (sorted by `wakeOrder`). That way the catalog and the wake order
 * can never drift apart: every night-active role gets its place solely via its
 * `wakeOrder` field.
 *
 * Ordering principle (app-specific, finer than the coarse rulebook order): since
 * roles are only bound to people when they first wake up, INFORMING roles
 * (Seer, Fox, Detective, …) deliberately wake up LATE — by then all other
 * night-active roles are already bound and can be checked correctly. Coarse bands:
 *   1x–2x  Setup/linking (Cupid, Sisters, Wild Child, Thief, Doppelganger …)
 *   3x–4x  Visiting/protection/control roles (Healer, Bodyguard, Jailer …)
 *   5x–6x  Pack & wolf team (Werewolves, Accursed Wolf Father, Minion, Wolf Shaman …)
 *   7x     Killing third parties & potions (Serial Killer, Vampire, Witch, Quack …)
 *   8x–10x Informing & closing roles (Seer, Phantom, Enchantress, Pied Piper …)
 */
function byWakeOrder(a: RoleDef, b: RoleDef): number {
  return (a.wakeOrder ?? Number.POSITIVE_INFINITY) - (b.wakeOrder ?? Number.POSITIVE_INFINITY)
}

/** All roles woken (individually) at night, in order — first night (incl. setup roles). */
export const FIRST_NIGHT_ORDER: string[] = ROLE_CATALOG.filter(
  (r) => r.wakesAtNight && r.wakeOrder !== null,
)
  .slice()
  .sort(byWakeOrder)
  .map((r) => r.id)

/** Later nights — without the pure setup roles (firstNightOnly). */
export const REGULAR_NIGHT_ORDER: string[] = ROLE_CATALOG.filter(
  (r) => r.wakesAtNight && !r.firstNightOnly && r.wakeOrder !== null,
)
  .slice()
  .sort(byWakeOrder)
  .map((r) => r.id)

